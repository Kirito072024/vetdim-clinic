const puppeteer = require('puppeteer-core');
const base = process.env.BASE_URL || 'http://localhost:4173';
const out = 'booking-success.png';
const w = 1280;
const wait = (ms) => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await puppeteer.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const p = await b.newPage();
  await p.setViewport({ width: +w || 1280, height: 900 });
  p.on('pageerror', e => console.log('PAGE ERROR:', e.message));
  p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('CONSOLE', m.type(), m.text()); });
  await p.goto(base + '/doctors?specialty=Терапевт', { waitUntil: 'networkidle0' });
  console.log('therapists:', await p.$$eval('.doctor-card', e => e.length), 'title:', await p.title());
  await p.click('.doctor-card a'); await wait(500);
  console.log('doctor page:', await p.$eval('h1', e => e.textContent), p.url());
  await p.click('.doctor__cta a'); await wait(500);
  console.log('booking step legend:', await p.$eval('legend', e => e.textContent));
  await p.click('.option'); await p.click('.booking__nav .btn--primary'); await wait(600);
  await p.click('.booking__nav .btn--primary'); await wait(600);
  console.log('step:', await p.$eval('legend', e => e.textContent), 'slots:', await p.$$eval('.slot:not(:disabled)', e => e.length));
  await p.click('.date:not(:disabled):nth-of-type(2)').catch(()=>{}); await wait(400);
  await p.click('.slot:not(:disabled)'); await p.click('.booking__nav .btn--primary'); await wait(300);
  await p.click('.booking__nav .btn--primary'); await wait(200);
  console.log('errors:', await p.$$eval('.field__error', e => e.map(x => x.textContent).filter(Boolean)));
  await p.type('#ownerName', 'Олена'); await p.type('#phone', '+380671234567'); await p.type('#petName', 'Рекс');
  await p.click('.booking__nav .btn--primary'); await wait(800);
  console.log('success:', await p.$eval('h1', e => e.textContent));
  await p.screenshot({ path: out });
  await p.goto(base + '/nope', { waitUntil: 'networkidle0' });
  console.log('404:', await p.$eval('h1', e => e.textContent));
  await b.close();
})();
